#!/usr/bin/env python3
"""Generate codegen/llvm/casemapsrc/normalize_tables.h — the Unicode
Normalization data String.prototype.normalize uses (UAX #15: NFC, NFD, NFKC,
NFKD).

Read off the interpreter's own Unicode database (unicodedata), as
gencasemap.py reads the case mappings, rather than from vendored
UnicodeData.txt/CompositionExclusions.txt. The Unicode version stamped into
the header is the interpreter's (unicodedata.unidata_version).

    python3 tools/gencasemap/gennormalize.py > codegen/llvm/casemapsrc/normalize_tables.h

Four tables come out (Hangul syllables are left to the algorithm):
  kml_norm_ccc     runs of code points with one nonzero canonical combining
                   class
  kml_norm_canon   each code point's full canonical decomposition (NFD of the
                   one code point), where it is not the code point itself
  kml_norm_compat  each code point's full compatibility decomposition (NFKD),
                   where it differs from the canonical one
  kml_norm_comp    the primary composites: (first, second) -> composite, for
                   each canonical pair decomposition NFC recomposes
"""
import unicodedata

MAX = 0x110000
SBASE, SCOUNT = 0xAC00, 11172


def skip(cp):
    return 0xD800 <= cp <= 0xDFFF or SBASE <= cp < SBASE + SCOUNT


ccc_runs = []
for cp in range(MAX):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = unicodedata.combining(chr(cp))
    if c == 0:
        continue
    if ccc_runs and ccc_runs[-1][1] == cp - 1 and ccc_runs[-1][2] == c:
        ccc_runs[-1][1] = cp
    else:
        ccc_runs.append([cp, cp, c])

pool = []
canon, compat = [], []
for cp in range(MAX):
    if skip(cp):
        continue
    ch = chr(cp)
    d = unicodedata.normalize("NFD", ch)
    k = unicodedata.normalize("NFKD", ch)
    if d != ch:
        canon.append((cp, len(pool), len(d)))
        pool.extend(ord(x) for x in d)
    if k != d:
        compat.append((cp, len(pool), len(k)))
        pool.extend(ord(x) for x in k)

comp = []
for cp in range(MAX):
    if skip(cp):
        continue
    raw = unicodedata.decomposition(chr(cp))
    if not raw or raw.startswith("<"):
        continue
    parts = [int(x, 16) for x in raw.split()]
    if len(parts) != 2:
        continue
    # Excluded (composition exclusions, singletons, non-starter
    # decompositions): NFC does not give the code point back.
    if unicodedata.normalize("NFC", chr(cp)) != chr(cp):
        continue
    comp.append((parts[0], parts[1], cp))
comp.sort()

out = []
w = out.append
w("/* Generated by tools/gencasemap/gennormalize.py - DO NOT EDIT.")
w("   Unicode %s (the generating Python's unicodedata). */" % unicodedata.unidata_version)
w('#define KML_NORMALIZE_UNICODE_VERSION "%s"' % unicodedata.unidata_version)
w("")
w("typedef struct { unsigned int lo, hi; unsigned char ccc; } KmlCccRange;")
w("static const KmlCccRange kml_norm_ccc[] = {")
for lo, hi, c in ccc_runs:
    w("  {0x%04X, 0x%04X, %d}," % (lo, hi, c))
w("};")
w("#define KML_NORM_CCC_N %d" % len(ccc_runs))
w("")
w("typedef struct { unsigned int cp; unsigned short off; unsigned char len; } KmlDecomp;")
w("static const unsigned int kml_norm_pool[] = {")
for i in range(0, len(pool), 12):
    w("  " + ", ".join("0x%04X" % x for x in pool[i:i + 12]) + ",")
w("};")
assert len(pool) < 65536
w("static const KmlDecomp kml_norm_canon[] = {")
for cp, off, n in canon:
    w("  {0x%04X, %d, %d}," % (cp, off, n))
w("};")
w("#define KML_NORM_CANON_N %d" % len(canon))
w("static const KmlDecomp kml_norm_compat[] = {")
for cp, off, n in compat:
    w("  {0x%04X, %d, %d}," % (cp, off, n))
w("};")
w("#define KML_NORM_COMPAT_N %d" % len(compat))
w("")
w("typedef struct { unsigned int a, b, c; } KmlComp;")
w("static const KmlComp kml_norm_comp[] = {")
for a, b, c in comp:
    w("  {0x%04X, 0x%04X, 0x%04X}," % (a, b, c))
w("};")
w("#define KML_NORM_COMP_N %d" % len(comp))
print("\n".join(out))
