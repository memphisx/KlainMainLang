// Every builtin on the global object, for a program that can see properties
// it does not name: its own module, so no other program compiles them.
import { hidden } from './internal_ns_object';
import { _kmlMath } from './internal_namespaces';
import { _kmlJSON } from './internal_ns_json';
import { _kmlReflect } from './internal_ns_reflect';
import { _kmlAtomics } from './internal_ns_atomics';
import { _kmlConsole } from './internal_ns_console';
import { _kmlGlobalThis } from './internal_global_object';
import { _kmlGlobalStructuredClone } from './internal_global_clone';

let globFilled = false;
export function _kmlGlobalThisFill(): void {
    if (globFilled) return;
    globFilled = true;
    const g: any = _kmlGlobalThis();
    delete g.globalThis;
    delete g.NaN;
    delete g.Infinity;
    delete g.undefined;
    g.clearImmediate = clearImmediate;
    g.setImmediate = setImmediate;
    g.clearInterval = clearInterval;
    g.clearTimeout = clearTimeout;
    g.setInterval = setInterval;
    g.setTimeout = setTimeout;
    g.queueMicrotask = queueMicrotask;
    g.structuredClone = function structuredClone(value: any, options?: any): any { return _kmlGlobalStructuredClone(value, options); };
    g.atob = atob;
    g.btoa = btoa;
    hidden(g, 'globalThis', g);
    hidden(g, 'Math', _kmlMath());
    hidden(g, 'JSON', _kmlJSON());
    hidden(g, 'Reflect', _kmlReflect());
    hidden(g, 'Atomics', _kmlAtomics());
    hidden(g, 'console', _kmlConsole());
    hidden(g, 'Object', Object);
    hidden(g, 'Function', Function);
    hidden(g, 'Array', Array);
    hidden(g, 'Number', Number);
    hidden(g, 'String', String);
    hidden(g, 'Boolean', Boolean);
    hidden(g, 'Symbol', Symbol);
    hidden(g, 'BigInt', BigInt);
    hidden(g, 'Date', Date);
    hidden(g, 'RegExp', RegExp);
    hidden(g, 'Error', Error);
    hidden(g, 'TypeError', TypeError);
    hidden(g, 'RangeError', RangeError);
    hidden(g, 'SyntaxError', SyntaxError);
    hidden(g, 'ReferenceError', ReferenceError);
    hidden(g, 'Promise', Promise);
    hidden(g, 'Map', Map);
    hidden(g, 'Set', Set);
    hidden(g, 'WeakMap', WeakMap);
    hidden(g, 'WeakSet', WeakSet);
    hidden(g, 'ArrayBuffer', ArrayBuffer);
    hidden(g, 'Uint8Array', Uint8Array);
    hidden(g, 'parseInt', parseInt);
    hidden(g, 'parseFloat', parseFloat);
    hidden(g, 'isNaN', isNaN);
    hidden(g, 'isFinite', isFinite);
    hidden(g, 'encodeURIComponent', encodeURIComponent);
    hidden(g, 'decodeURIComponent', decodeURIComponent);
    hidden(g, 'encodeURI', encodeURI);
    hidden(g, 'decodeURI', decodeURI);
    // Node's other own globals this runtime implements natively (the
    // global modules' classes are linked in by codegen).
    hidden(g, 'AggregateError', AggregateError);
    hidden(g, 'EvalError', EvalError);
    hidden(g, 'URIError', URIError);
    hidden(g, 'Int8Array', Int8Array);
    hidden(g, 'Uint8ClampedArray', Uint8ClampedArray);
    hidden(g, 'Uint16Array', Uint16Array);
    hidden(g, 'Int16Array', Int16Array);
    hidden(g, 'Uint32Array', Uint32Array);
    hidden(g, 'Int32Array', Int32Array);
    hidden(g, 'Float32Array', Float32Array);
    hidden(g, 'Float64Array', Float64Array);
    hidden(g, 'BigInt64Array', BigInt64Array);
    hidden(g, 'BigUint64Array', BigUint64Array);
    hidden(g, 'SharedArrayBuffer', SharedArrayBuffer);
    hidden(g, 'Proxy', Proxy);
    hidden(g, 'FinalizationRegistry', FinalizationRegistry);
    hidden(g, 'escape', escape);
    hidden(g, 'unescape', unescape);
    hidden(g, 'NaN', NaN);
    hidden(g, 'Infinity', Infinity);
    hidden(g, 'undefined', undefined);
}
