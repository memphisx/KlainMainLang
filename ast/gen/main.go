// Command gen writes ast/walk_generated.go: ForEachChild for every AST node,
// derived from the struct definitions in ast/nodes.go and ast/type_nodes.go, so
// the traversal can never fall out of step with the node set. A node kind or a
// child field added to either file is walked as soon as `go generate ./ast`
// runs; TestWalkGenerated fails until it does.
//
// A child is a field whose type is Node or an interface embedding it
// (Expression, Statement, TypeNode, …), a pointer to a node struct, a helper
// struct (by value or pointer) that contains children, or a slice of any of
// those. Excluded: the TypeAnnotation shim (converted from type nodes, which
// are reached only through its Node field), and the Program fields that alias
// nodes already in the body or hold separately-walked module bodies
// (skipFields).
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
)

// skipTypes are never traversed.
var skipTypes = map[string]bool{"TypeAnnotation": true, "Pos": true}

// skipFields are node fields that are not children: aliases of nodes reached
// through the body, or bodies of other modules.
var skipFields = map[string]bool{
	"Program.DynamicImportNodes":    true, // the same nodes appear in Body
	"Program.WorkerModules":         true, // separate module bodies, walked explicitly
	"Program.NamespaceGroups":       true, // the same statements appear in Body
	"FunctionDeclaration.Overloads": true, // signatures only: no code to walk
}

type field struct {
	name string
	typ  ast.Expr
}

func main() {
	out := "walk_generated.go"
	srcs := []string{"nodes.go", "type_nodes.go"}
	if len(os.Args) >= 3 {
		out, srcs = os.Args[1], os.Args[2:]
	}
	code, err := Generate(srcs...)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(out, code, 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// Generate returns the formatted walk_generated.go for the AST in srcs.
func Generate(srcs ...string) ([]byte, error) {
	fset := token.NewFileSet()
	var decls []ast.Decl
	for _, src := range srcs {
		f, err := parser.ParseFile(fset, src, nil, 0)
		if err != nil {
			return nil, err
		}
		decls = append(decls, f.Decls...)
	}
	structs := map[string][]field{}
	var order []string
	nodes := map[string]bool{}
	ifaces := map[string]bool{"Node": true} // interfaces a child may be held in
	for _, d := range decls {
		switch d := d.(type) {
		case *ast.GenDecl:
			for _, s := range d.Specs {
				ts, ok := s.(*ast.TypeSpec)
				if !ok {
					continue
				}
				if it, ok := ts.Type.(*ast.InterfaceType); ok {
					for _, m := range it.Methods.List {
						if id, ok := m.Type.(*ast.Ident); ok && len(m.Names) == 0 && id.Name == "Node" {
							ifaces[ts.Name.Name] = true
						}
					}
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				var fs []field
				for _, fl := range st.Fields.List {
					for _, nm := range fl.Names {
						if ast.IsExported(nm.Name) {
							fs = append(fs, field{nm.Name, fl.Type})
						}
					}
					if len(fl.Names) == 0 {
						return nil, fmt.Errorf("%s: embedded fields are not supported by the walker generator", ts.Name.Name)
					}
				}
				structs[ts.Name.Name] = fs
				order = append(order, ts.Name.Name)
			}
		case *ast.FuncDecl:
			if d.Recv != nil && d.Name.Name == "nodeMarker" {
				t := d.Recv.List[0].Type
				if se, ok := t.(*ast.StarExpr); ok {
					t = se.X
				}
				nodes[t.(*ast.Ident).Name] = true
			}
		}
	}

	// holds[T]: helper struct T (transitively) contains a child.
	holds := map[string]bool{}
	var childType func(t ast.Expr, seen map[string]bool) bool
	var helperHolds func(name string, seen map[string]bool) bool
	helperHolds = func(name string, seen map[string]bool) bool {
		if v, ok := holds[name]; ok {
			return v
		}
		if seen[name] || skipTypes[name] || nodes[name] {
			return false
		}
		seen[name] = true
		for _, fl := range structs[name] {
			if childType(fl.typ, seen) {
				holds[name] = true
				return true
			}
		}
		return false
	}
	childType = func(t ast.Expr, seen map[string]bool) bool {
		switch t := t.(type) {
		case *ast.Ident:
			if ifaces[t.Name] {
				return true
			}
			if _, ok := structs[t.Name]; ok && !nodes[t.Name] {
				return helperHolds(t.Name, seen)
			}
		case *ast.StarExpr:
			if id, ok := t.X.(*ast.Ident); ok {
				if nodes[id.Name] {
					return true
				}
				return childType(id, seen)
			}
		case *ast.ArrayType:
			return childType(t.Elt, seen)
		}
		return false
	}
	for _, n := range order {
		helperHolds(n, map[string]bool{})
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by ast/gen from nodes.go and type_nodes.go; DO NOT EDIT.\n\npackage ast\n\n")
	b.WriteString("// ForEachChild calls visit on each direct child of n, in field order, skipping\n")
	b.WriteString("// absent (nil) children, and stops at the first visit that returns false. It\n")
	b.WriteString("// reports whether every visit returned true.\n")
	b.WriteString("func ForEachChild(n Node, visit func(Node) bool) bool {\n\tswitch n := n.(type) {\n")
	var nodeNames []string
	for _, n := range order {
		if nodes[n] {
			nodeNames = append(nodeNames, n)
		}
	}
	for _, n := range nodeNames {
		var body strings.Builder
		for _, fl := range structs[n] {
			if skipFields[n+"."+fl.name] || !childType(fl.typ, map[string]bool{}) {
				continue
			}
			emitVisit(&body, "n."+fl.name, fl.typ, nodes, ifaces)
		}
		if body.Len() == 0 {
			continue
		}
		fmt.Fprintf(&b, "\tcase *%s:\n%s", n, body.String())
	}
	b.WriteString("\t}\n\treturn true\n}\n\n")

	b.WriteString("// RewriteChildren replaces each direct child c of n with rewrite(c), in field\n")
	b.WriteString("// order, skipping absent children. A child held in an Expression, Statement or\n")
	b.WriteString("// Node field may be replaced by any node of that interface; a child held in a\n")
	b.WriteString("// concretely-typed field must be replaced by a node of the same type.\n")
	b.WriteString("func RewriteChildren(n Node, rewrite func(Node) Node) {\n\tswitch n := n.(type) {\n")
	for _, n := range nodeNames {
		var body strings.Builder
		for _, fl := range structs[n] {
			if skipFields[n+"."+fl.name] || !childType(fl.typ, map[string]bool{}) {
				continue
			}
			emitRewrite(&body, "n."+fl.name, fl.typ, nodes, ifaces)
		}
		if body.Len() == 0 {
			continue
		}
		fmt.Fprintf(&b, "\tcase *%s:\n%s", n, body.String())
	}
	b.WriteString("\t}\n}\n\n")

	var helpers []string
	for h, ok := range holds {
		if ok {
			helpers = append(helpers, h)
		}
	}
	sort.Strings(helpers)
	for _, h := range helpers {
		fmt.Fprintf(&b, "func rewrite%s(x *%s, rewrite func(Node) Node) {\n", h, h)
		for _, fl := range structs[h] {
			if !childType(fl.typ, map[string]bool{}) {
				continue
			}
			var body strings.Builder
			emitRewrite(&body, "x."+fl.name, fl.typ, nodes, ifaces)
			b.WriteString(body.String())
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "func visit%s(x *%s, visit func(Node) bool) bool {\n", h, h)
		for _, fl := range structs[h] {
			if !childType(fl.typ, map[string]bool{}) {
				continue
			}
			var body strings.Builder
			emitVisit(&body, "x."+fl.name, fl.typ, nodes, ifaces)
			b.WriteString(body.String())
		}
		b.WriteString("\treturn true\n}\n\n")
	}
	fmt.Fprintf(&b, "// nodeKinds is every node type the walker knows, for tests.\nvar nodeKinds = []string{%s}\n", quoteAll(nodeNames))
	return format.Source(b.Bytes())
}

func quoteAll(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = fmt.Sprintf("%q", x)
	}
	return strings.Join(q, ", ")
}

// emitRewrite writes the code rewriting expr (of type t) in place.
func emitRewrite(b *strings.Builder, expr string, t ast.Expr, nodes, ifaces map[string]bool) {
	switch t := t.(type) {
	case *ast.Ident:
		switch {
		case ifaces[t.Name]:
			fmt.Fprintf(b, "\t\tif present(%s) {\n\t\t\t%s = rewrite(%s).(%s)\n\t\t}\n", expr, expr, expr, t.Name)
		default: // helper struct by value
			fmt.Fprintf(b, "\t\trewrite%s(&%s, rewrite)\n", t.Name, expr)
		}
	case *ast.StarExpr:
		id := t.X.(*ast.Ident)
		if nodes[id.Name] {
			fmt.Fprintf(b, "\t\tif %s != nil {\n\t\t\t%s = rewrite(%s).(*%s)\n\t\t}\n", expr, expr, expr, id.Name)
		} else {
			fmt.Fprintf(b, "\t\tif %s != nil {\n\t\t\trewrite%s(%s, rewrite)\n\t\t}\n", expr, id.Name, expr)
		}
	case *ast.ArrayType:
		fmt.Fprintf(b, "\t\tfor i := range %s {\n", expr)
		var inner strings.Builder
		emitRewrite(&inner, expr+"[i]", t.Elt, nodes, ifaces)
		b.WriteString(inner.String())
		b.WriteString("\t\t}\n")
	}
}

// emitVisit writes the code visiting expr (of type t).
func emitVisit(b *strings.Builder, expr string, t ast.Expr, nodes, ifaces map[string]bool) {
	switch t := t.(type) {
	case *ast.Ident:
		switch {
		case ifaces[t.Name]:
			fmt.Fprintf(b, "\t\tif present(%s) && !visit(%s) {\n\t\t\treturn false\n\t\t}\n", expr, expr)
		default: // helper struct by value
			fmt.Fprintf(b, "\t\tif !visit%s(&%s, visit) {\n\t\t\treturn false\n\t\t}\n", t.Name, expr)
		}
	case *ast.StarExpr:
		id := t.X.(*ast.Ident)
		if nodes[id.Name] {
			fmt.Fprintf(b, "\t\tif %s != nil && !visit(%s) {\n\t\t\treturn false\n\t\t}\n", expr, expr)
		} else {
			fmt.Fprintf(b, "\t\tif %s != nil && !visit%s(%s, visit) {\n\t\t\treturn false\n\t\t}\n", expr, id.Name, expr)
		}
	case *ast.ArrayType:
		fmt.Fprintf(b, "\t\tfor i := range %s {\n", expr)
		var inner strings.Builder
		emitVisit(&inner, expr+"[i]", t.Elt, nodes, ifaces)
		b.WriteString(strings.ReplaceAll(inner.String(), "\n\t\t", "\n\t\t\t"))
		b.WriteString("\t\t}\n")
	}
}
